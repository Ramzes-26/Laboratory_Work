#include<iostream> // Подключение библиотеки
#include<clocale>  //  Для русского языка в консоли
int main() {
	setlocale(LC_ALL, "RU"); // Включаем русский язык
	std::cout << "Распознаю трёхзначные числа!";// Заголовок
	int a;
	std::cout << "\nВведите любое число: ";
	std::cin >> a;  // Ввод числа

	// Проверка: является ли число трёхзначным?
	// Трёхзначное число — от 100 до 999 включительно.
	// Оператор && (логическое И) требует, чтобы ОБА условия были истинны:
	//   a >= 100 — число не меньше 100
	//   a <= 999 — число не больше 999
	// Если оба условия истинны — число трёхзначное.
	if (a >= 100 && a <= 999) {
		std::cout << "Число " << a << " - Трёхзначное!\n";
	}
	else {
		// Если хотя бы одно из условий ложно — число НЕ трёхзначное.
		// Сюда попадают: числа меньше 100 (1-, 2-значные, 0, отрицательные)
		// и числа больше 999 (4-значные и более).
		std::cout << "Число " << a << " - НЕ трёхзначное!\n";
	}
	return 0; // Успешное завершение программы
}