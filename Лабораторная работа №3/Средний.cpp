#include<iostream> // Библиотека ввода-вывода (cin, cout)
#include<clocale> // Библиотека для русского языка в консоли
int main() {
	// Включаем поддержку русского языка в консоли
	setlocale(LC_ALL, "RU");
	// Заголовок программы
	std::cout << "Калькулятор!";
	// Объявляем переменные:
	// a, b — два числа для вычислений (тип double — для дробных чисел)
	// c — символ операции (+, -, *, /)
	double a, b;
	char c;
	// Ввод первого числа
	std::cout << "\nВведите первое число: ";
	std::cin >> a;
	// Ввод второго числа
	std::cout << "Введите второе число: ";
	std::cin >> b;
	// Ввод символа операции
	std::cout << "Введите символ операции : ";
	std::cin >> c;
	// Проверяем, какая операция введена, и выполняем её:
	if (c == '+') {
		// Операция сложения
		std::cout << a << " + " << b << " = " << a + b << "\n";
	}
	else if (c == '-') {
		// Операция вычитания
		std::cout << a << " - " << b << " = " << a - b << "\n";
	}
	else if (c == '*') {
		// Операция умножения
		std::cout << a << " * " << b << " = " << a * b << "\n";
	}
	else if (c == '/') {
		// Операция деления — требует проверки делителя

		// Вложенный if: проверяем, не равен ли делитель нулю
		if (b == 0) {
			// Деление на ноль невозможно — выводим сообщение об ошибке
			std::cout << "Деление на ноль невозможно!";
		}
		else {
			// Делитель не ноль — выполняем деление
			std::cout << a << " / " << b << " = " << a / b << "\n";
		}
	}
	else {
		// Сюда попадаем, если введён неизвестный символ операции
	    // (например, %, x, @ или буква)
		std::cout << "Ошибка: неизвестная операция!";
	}
	    // Успешное завершение программы
	return 0;
}