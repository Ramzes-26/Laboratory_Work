#include<iostream>
#include<clocale>
int main() {
	setlocale(LC_ALL, "RU");
	std::cout << "Перевод градусов!\n";
	// const double PI — константа, значение не меняется.
	// const защищает от случайного изменения и говорит компилятору,
	// что это неизменяемая величина.
	const double PI = 3.1415926535;
	// int a — целое число градусов, введённое пользователем.
	int a;
	std::cout << "Введите градусы: ";
	std::cin >> a;
	// Проверка: угол должен быть положительным.
	if (a > 0) {
		// НЕЯВНОЕ ПРИВЕДЕНИЕ: int a автоматически превращается в double,
		// потому что переменная gradus имеет тип double.
		// Компилятор сам делает приведение — static_cast не нужен.
		double gradus = a;
		// Формула перевода градусов в радианы: радианы = градусы * π / 180.
		// Здесь тоже неявное приведение: PI и 180 участвуют в выражении с double.
		double c = gradus * PI / 180;
		std::cout << "Радианы: " << c << "\n";
		std::cout << "Градусы " << c * 180 / PI << '\n';
	}
	else {
		std::cout << "Введите корректные данные!\n";
	}
	return 0;
}