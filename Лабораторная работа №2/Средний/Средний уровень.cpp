#include<iostream>
#include<clocale>
#include<cmath> // для sqrt
int main() {
	setlocale(LC_ALL, "RU");
	std::cout << "Вычисление гипотенузы по двум катетам!\n";
	// Тип int выбран, потому что задание требует продемонстрировать
   // static_cast<double> — приведение int к double имеет смысл.
   // Если бы катеты были double, приведение было бы бессмысленным.
	int a, b;
	std::cout << "Введите первый катет: ";
	std::cin >> a;
	std::cout << "Введите второй катет: ";
	std::cin >> b;
	// Проверка: катеты должны быть положительными.
	// Гипотенуза имеет смысл только для положительных длин.
	if (a > 0 && b > 0) {
		// Формула: c = sqrt(a² + b²)
		// static_cast<double> нужен, чтобы результат sqrt был типа double
		// (хотя sqrt и так возвращает double, приведение показывает
		//  явное понимание типов и требуются заданием).
		std::cout << "Ответ: " << static_cast<double>(sqrt(a * a + b * b)) << "\n";
	}
	else {
		std::cout << "Введите корректные данные!";
	}
	return 0;
}